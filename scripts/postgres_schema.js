async function migrate() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL no configurada');
  }

  const client = new Client(getConnectionOptions(process.env.DATABASE_URL));

  await client.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(724319)');
    for (const statement of statements) {
      await client.query(statement);
    }
    await client.query('INSERT INTO schema_migrations (version) VALUES (1) ON CONFLICT (version) DO NOTHING');
    const versionResult = await client.query('SELECT COALESCE(MAX(version), 0)::integer AS version FROM schema_migrations');
    if (versionResult.rows[0].version < 2) {
      for (const statement of versionTwoStatements) {
        await client.query(statement);
      }
      await client.query('INSERT INTO schema_migrations (version) VALUES (2) ON CONFLICT (version) DO NOTHING');
    }
    await client.query('COMMIT');
    console.log('Esquema PostgreSQL aplicado correctamente');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    await client.end();
  }
}

if (require.main === module) {
  migrate().catch((error) => {
    console.error('Error de migración PostgreSQL:', error.code || error.message);
    process.exit(1);
  });
}

